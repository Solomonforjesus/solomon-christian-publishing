/* Scripture previews for ministry writing. Existing Solomon chat owns its integration. */
(function () {
  "use strict";
  if (window.solomonWritingPreviews) return;
  window.solomonWritingPreviews = true;
  const source = document.currentScript;
  const selector = source && source.dataset.scriptureRoots;
  const roots = selector ? Array.from(document.querySelectorAll(selector)) : [document.querySelector("main") || document.body];
  if (!roots.length) return;
  // Reuse the existing public tagging entry point without changing chat code or settings.
  if (typeof window.tagChatScripture === "function") {
    roots.forEach(root => window.tagChatScripture(root));
    return;
  }
    // Logos supplies verified Scripture previews; no Bible text is generated by the AI.
    window.refTagger = { settings: {
      bibleVersion: "NKJV", tagAutomatically: false, observeAutomatically: false,
      rootNode: document.body, noSearchTagNames: ["script", "style", "textarea", "input", "select", "option", "button", "label", "code", "pre"],
      linksOpenNewWindow: true, socialSharing: [], roundCorners: true,
      tagChapters: true, caseInsensitive: true
    }};
    const preparedLinks = new WeakSet();
    const scriptureSettings = window.refTagger.settings;
    let scriptureReady = false, scriptureFailed = false, activeScripture = null;
    let previewPinned = false;
    const scriptureQueue = new Set();

    function tagChatScripture(body) {
      if (scriptureReady) {
        window.refTagger.tag(body);
        body.querySelectorAll("a.rtBibleRef").forEach(prepareScriptureLink);
      } else if (scriptureFailed) fallbackScriptureLinks(body);
      else scriptureQueue.add(body);
    }

    function fallbackScriptureLinks(body) {
      const books = "Genesis|Exodus|Leviticus|Numbers|Deuteronomy|Joshua|Judges|Ruth|[123]\\s+(?:Samuel|Kings|Chronicles|Corinthians|Thessalonians|Timothy|Peter|John)|Ezra|Nehemiah|Esther|Job|Psalms?|Proverbs|Ecclesiastes|Song of (?:Solomon|Songs)|Isaiah|Jeremiah|Lamentations|Ezekiel|Daniel|Hosea|Joel|Amos|Obadiah|Jonah|Micah|Nahum|Habakkuk|Zephaniah|Haggai|Zechariah|Malachi|Matthew|Mark|Luke|John|Acts|Romans|Galatians|Ephesians|Philippians|Colossians|Titus|Philemon|Hebrews|James|Jude|Revelation";
      const pattern = new RegExp("\\b(?:" + books + ")\\s+\\d{1,3}(?::\\d{1,3}(?:\\s*[-–]\\s*\\d{1,3}(?::\\d{1,3})?)?)?\\b", "gi");
      const walker = document.createTreeWalker(body, NodeFilter.SHOW_TEXT);
      const nodes = []; while (walker.nextNode()) if (!walker.currentNode.parentElement.closest("a,script,style,textarea,input,select,button,label,code,pre")) nodes.push(walker.currentNode);
      nodes.forEach(node => {
        const fragment = document.createDocumentFragment(); let cursor = 0;
        for (const match of node.textContent.matchAll(pattern)) {
          fragment.append(document.createTextNode(node.textContent.slice(cursor, match.index)));
          const a = document.createElement("a"); a.className = "scripture-link";
          a.textContent = match[0]; a.href = "https://biblia.com/bible/nkjv/" + encodeURIComponent(match[0]);
          a.target = "_blank"; a.rel = "noopener noreferrer"; a.title = "Read " + match[0] + " (NKJV) in a new tab";
          fragment.append(a); cursor = match.index + match[0].length;
        }
        fragment.append(document.createTextNode(node.textContent.slice(cursor))); node.replaceWith(fragment);
      });
    }

    function dismissScripturePreview(restoreFocus = false) {
      const anchor = activeScripture;
      previewPinned = false;
      document.querySelectorAll(".rtTooltip").forEach(node => node.remove());
      if (anchor) { anchor.setAttribute("aria-expanded", "false"); anchor.removeAttribute("aria-controls"); }
      activeScripture = null;
      if (restoreFocus && anchor) { anchor.dataset.skipFocusPreview = "true"; anchor.focus(); }
    }

    function prepareScriptureLink(a) {
      if (preparedLinks.has(a)) return;
      preparedLinks.add(a);
      a.classList.add("scripture-link"); a.rel = "noopener noreferrer";
      a.setAttribute("aria-haspopup", "dialog"); a.setAttribute("aria-expanded", "false");
      a.setAttribute("aria-label", a.textContent + " — Scripture preview; full passage opens in a new tab");
      const activate = () => {
        if (activeScripture && activeScripture !== a) { activeScripture.setAttribute("aria-expanded", "false"); previewPinned = false; }
        activeScripture = a;
      };
      a.addEventListener("mouseover", activate);
      a.addEventListener("focus", () => {
        if (a.dataset.skipFocusPreview) { delete a.dataset.skipFocusPreview; return; }
        activate(); a.dispatchEvent(new MouseEvent("mouseover", { bubbles: true }));
      });
      a.addEventListener("click", event => {
        if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
        event.preventDefault(); activate(); previewPinned = true;
        a.dispatchEvent(new MouseEvent("mouseover", { bubbles: true }));
      });
      a.addEventListener("keydown", event => {
        if (event.key === " ") { event.preventDefault(); a.click(); }
        if (event.key === "ArrowDown") {
          const close = document.querySelector(".scripture-preview-close");
          if (close) { event.preventDefault(); close.focus(); }
        }
        if (event.key === "Tab" && !event.shiftKey) {
          const close = document.querySelector(".scripture-preview-close");
          if (close) { event.preventDefault(); close.focus(); }
        }
      });
      // A clicked preview stays open until explicitly dismissed.
      a.addEventListener("mouseout", event => {
        if (previewPinned && activeScripture === a) event.stopImmediatePropagation();
      }, true);
    }

    function enhanceScripturePreview(tooltip) {
      if (!activeScripture) { tooltip.remove(); return; }
      tooltip.id = "solomon-scripture-preview";
      tooltip.setAttribute("role", "dialog"); tooltip.setAttribute("aria-label", "Scripture preview");
      activeScripture.setAttribute("aria-expanded", "true"); activeScripture.setAttribute("aria-controls", tooltip.id);
      if (!tooltip.dataset.enhanced) {
        tooltip.dataset.enhanced = "true";
        tooltip.addEventListener("mouseout", event => {
          if (previewPinned || tooltip.contains(event.relatedTarget)) event.stopImmediatePropagation();
        }, true);
        tooltip.addEventListener("keydown", event => {
          const controls = Array.from(tooltip.querySelectorAll("button, a[href]"));
          if (event.key === "Tab" && ((event.shiftKey && event.target === controls[0]) || (!event.shiftKey && event.target === controls.at(-1)))) {
            event.preventDefault(); dismissScripturePreview(true);
          }
        });
      }
      const content = tooltip.querySelector(".rtTooltipBody");
      // RefTagger includes cross-reference and footnote labels as verse-ref spans.
      // Remove those annotation nodes before excerpting; retain verse numbers and text.
      content?.querySelectorAll(".resourcetext .verse-ref").forEach(marker => marker.remove());
      if (content && !content.dataset.shortened && content.querySelector(".resourcetext")) {
        content.dataset.shortened = "true";
        const words = content.textContent.trim().split(/\s+/);
        if (words.length > 50) {
          content.textContent = words.slice(0, 50).join(" ") + "…";
          const note = document.createElement("small"); note.className = "scripture-excerpt-note";
          note.textContent = "Opening excerpt · Read the full passage below."; content.append(note);
        }
      }
      if (!tooltip.querySelector(".scripture-preview-close")) {
        const close = document.createElement("button"); close.type = "button"; close.className = "scripture-preview-close";
        close.textContent = "Close"; close.addEventListener("click", () => dismissScripturePreview(true));
        (tooltip.querySelector(".rtContainer") || tooltip).prepend(close);
      }
      tooltip.querySelectorAll("a").forEach(a => { a.target = "_blank"; a.rel = "noopener noreferrer"; });
      const more = tooltip.querySelector(".rtTooltipMoreLink");
      if (more && more.textContent !== "Read full passage ↗") more.textContent = "Read full passage ↗";
      const version = tooltip.querySelector(".rtTooltipHeader")?.textContent.match(/\(([A-Z0-9]+)\)/)?.[1];
      if (content && version && !content.querySelector(".scripture-version-note")) {
        const attribution = document.createElement("small"); attribution.className = "scripture-version-note";
        attribution.textContent = "— " + version; content.append(attribution);
      }
      // Keep a working passage link even if the provider cannot load the preview.
      if (content && !content.querySelector(".resourcetext") && !content.dataset.shortened && !more && !/loading/i.test(tooltip.textContent)) {
        const fallback = document.createElement("a"); fallback.className = "rtTooltipMoreLink";
        fallback.href = activeScripture.href; fallback.target = "_blank"; fallback.rel = "noopener noreferrer";
        fallback.textContent = "Read full passage ↗"; tooltip.append(fallback);
      }
      const header = tooltip.querySelector(".rtTooltipHeader");
      if (header) tooltip.setAttribute("aria-label", header.textContent.trim() + " Scripture preview");
      // Anchor to the viewport so the chat's scrolling container cannot clip the preview.
      const rect = activeScripture.getBoundingClientRect();
      const width = tooltip.getBoundingClientRect().width;
      tooltip.style.position = "fixed";
      tooltip.style.left = Math.max(8, Math.min(rect.left, window.innerWidth - width - 8)) + "px";
      const height = tooltip.getBoundingClientRect().height;
      const below = rect.bottom + 8;
      tooltip.style.top = Math.max(8, below + height <= window.innerHeight - 8 ? below : rect.top - height - 8) + "px";
    }

    new MutationObserver(records => {
      const changed = new Set();
      for (const record of records) {
        if (record.target.nodeType === 1) {
          const parent = record.target.closest(".rtTooltip"); if (parent) changed.add(parent);
        }
        for (const node of record.addedNodes) {
          if (node.nodeType === 1 && node.matches(".rtTooltip")) changed.add(node);
        }
        for (const node of record.removedNodes) {
          if (node.nodeType === 1 && node.matches(".rtTooltip") && activeScripture && !document.querySelector(".rtTooltip")) activeScripture.setAttribute("aria-expanded", "false");
        }
      }
      changed.forEach(tooltip => { if (tooltip.isConnected) enhanceScripturePreview(tooltip); });
    }).observe(document.body, { childList: true, subtree: true });
    document.addEventListener("pointerdown", event => {
      if (!event.target.closest(".rtTooltip, .scripture-link")) dismissScripturePreview();
    });
    document.addEventListener("keydown", event => { if (event.key === "Escape") dismissScripturePreview(true); });
    document.addEventListener("focusin", event => {
      if (!event.target.closest(".rtTooltip, .scripture-link")) dismissScripturePreview();
    });
    window.addEventListener("scroll", () => { if (!previewPinned) dismissScripturePreview(); }, { passive: true });
    window.addEventListener("resize", () => dismissScripturePreview());
    const scriptureScript = document.createElement("script");
    scriptureScript.src = "https://api.reftagger.com/v2/RefTagger.js"; scriptureScript.async = true;
    scriptureScript.onload = () => {
      scriptureReady = typeof window.refTagger.tag === "function";
      if (!scriptureReady) { scriptureScript.onerror(); return; }
      window.refTagger.init(scriptureSettings);
      scriptureQueue.clear();
      scanWriting();
    };
    scriptureScript.onerror = () => {
      scriptureFailed = true;
      scriptureQueue.forEach(body => { if (body.isConnected) fallbackScriptureLinks(body); }); scriptureQueue.clear();
    };
    document.head.append(scriptureScript);
  let scanTimer;
  const writingObserver = new MutationObserver(records => {
    const changed = records.some(record => {
      const element = record.target.nodeType === 1 ? record.target : record.target.parentElement;
      return element && !element.closest(".rtTooltip, a.rtBibleRef, script, style, textarea, input, select, button, label, code, pre");
    });
    if (!changed) return;
    clearTimeout(scanTimer);
    scanTimer = setTimeout(scanWriting, 80);
  });
  function observeWriting() {
    roots.forEach(root => writingObserver.observe(root, {childList: true, characterData: true, subtree: true}));
  }
  function scanWriting() {
    writingObserver.disconnect();
    try { roots.forEach(root => { if (root.isConnected) tagChatScripture(root); }); }
    finally { observeWriting(); }
  }
  scanWriting();
})();
